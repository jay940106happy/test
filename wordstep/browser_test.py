"""Browser checks; speech hardware is replaced only to inspect the utterance requests."""
import functools
import http.server
import json
import pathlib
import threading
from playwright.sync_api import sync_playwright

ROOT=pathlib.Path(__file__).resolve().parent.parent
QA=ROOT/'qa'
QA.mkdir(exist_ok=True)
handler=functools.partial(http.server.SimpleHTTPRequestHandler,directory=str(ROOT/'docs'))
server=http.server.ThreadingHTTPServer(('127.0.0.1',0),handler)
threading.Thread(target=server.serve_forever,daemon=True).start()
url=f'http://127.0.0.1:{server.server_port}/index.html'
results=[]
def check(label,value):
    if not value: raise AssertionError(label)
    results.append(label)
mock="""window.__spoken=[];window.__cancelled=0;window.__utterances=[];Object.defineProperty(window,'speechSynthesis',{value:{getVoices:()=>[{name:'English',lang:'en-US',voiceURI:'en-US'}],addEventListener:()=>{},cancel:()=>{window.__cancelled++;},speak:u=>{window.__spoken.push({text:u.text,rate:u.rate,lang:u.lang});window.__utterances.push(u);if(u.onstart)u.onstart();}}});window.SpeechSynthesisUtterance=function(text){this.text=text;};"""
with sync_playwright() as p:
    b=p.chromium.launch()
    page=b.new_page(viewport={'width':390,'height':844},device_scale_factor=1)
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.add_init_script(mock)
    page.goto(url)
    check('full dataset',page.locator('#total').inner_text()=='1,000 字詞' and page.locator('#word-jump option').count()==1000)
    check('two examples',page.locator('.example').count()==2)
    check('initial word',page.locator('#word').inner_text()=='office')
    page.screenshot(path=str(QA/'mobile.png'),full_page=True)
    page.locator('#search').fill('確認')
    check('Chinese search',0<page.locator('#word-jump option').count()<1000)
    page.locator('#search').fill('résumé')
    check('accent search',page.locator('#word').inner_text()=='résumé')
    page.locator('#search').fill('resume')
    check('ASCII accent search',page.locator('#word').inner_text()=='résumé')
    page.locator('#search').fill('')
    page.locator('#tools').evaluate('(e)=>e.open=true')
    page.select_option('#category','飯店與住宿')
    check('50 category entries',page.locator('#word-jump option').count()==50)
    page.select_option('#word-jump','w0787')
    check('direct jump',page.locator('#word').inner_text()=='keycard')
    page.locator('#known').click()
    check('mark known',page.locator('#known').get_attribute('aria-pressed')=='true')
    page.reload()
    check('saved selected',page.locator('#word').inner_text()=='keycard')
    check('saved known',page.locator('#known').get_attribute('aria-pressed')=='true')
    page.locator('#hide-chinese').click()
    check('hide translation',page.locator('#meaning').evaluate('(e)=>getComputedStyle(e).visibility')=='hidden')
    page.locator('#hide-chinese').click()
    check('show translation',page.locator('#meaning').evaluate('(e)=>getComputedStyle(e).visibility')=='visible')
    page.locator('[data-play="word"]').click()
    check('word speech',page.evaluate('window.__spoken.at(-1).text')=='keycard')
    page.locator('[data-play="example0"]').click()
    check('first example speech',page.evaluate('window.__spoken.at(-1).text')==page.locator('.example .en').nth(0).inner_text())
    page.locator('[data-play="example1"]').click()
    check('second example speech',page.evaluate('window.__spoken.at(-1).text')==page.locator('.example .en').nth(1).inner_text())
    page.locator('[data-play="example1"]').click()
    check('stop same speech',page.locator('[data-play="example1"]').get_attribute('aria-pressed')=='false')
    page.evaluate('window.__spoken=[]')
    page.locator('#play-all').click()
    check('whole group 3 utterances',len(page.evaluate('window.__spoken'))==3)
    page.locator('#slow').uncheck()
    page.locator('[data-play="word"]').click()
    check('normal speed',page.evaluate('window.__spoken.at(-1).rate')==1)
    page.locator('#slow').check()
    page.locator('[data-play="word"]').click()
    check('slow speed',page.evaluate('window.__spoken.at(-1).rate')==.7)
    page.locator('#next').click()
    check('next stops speech',page.locator('.playing').count()==0)
    page.locator('#tools').evaluate('(e)=>e.open=true')
    page.select_option('#filter','known')
    check('known-only filter',page.locator('#word-jump option').count()==1)
    page.select_option('#filter','new')
    check('new-only filter',page.locator('#word-jump option').count()==999)
    page.locator('#clear-filters').click()
    page.locator('#tools').evaluate('(e)=>e.open=false')
    page.locator('#search').fill('zzzzzzzzz')
    check('empty state',page.locator('#empty').is_visible())
    page.locator('#empty-clear').click()
    check('clear empty filter',page.locator('#word-jump option').count()==1000)
    for width in [320,390,1280]:
        page.set_viewport_size({'width':width,'height':900 if width>500 else 844})
        check(f'no overflow {width}',page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
        if width==1280: page.screenshot(path=str(QA/'desktop.png'),full_page=True)
    page.set_viewport_size({'width':390,'height':844})
    page.locator('#tools').evaluate('(e)=>e.open=true')
    page.screenshot(path=str(QA/'tools-mobile.png'),full_page=True)
    check('no JS errors',errors==[])
    # Real browser storage: load the old 16-entry identifiers, then reload with new IDs.
    context=b.new_context()
    legacy=context.new_page()
    legacy.goto(url)
    legacy.evaluate("localStorage.setItem('wordstep.progress.v1',JSON.stringify({meeting:true}));localStorage.setItem('wordstep.preferences.v1',JSON.stringify({selected:'meeting'}));")
    legacy.reload()
    check('legacy selected migration',legacy.locator('#word').inner_text()=='meeting')
    check('legacy known migration',legacy.locator('#known').get_attribute('aria-pressed')=='true')
    legacy.locator('#known').click()
    legacy.reload()
    check('legacy unmark persists',legacy.locator('#known').get_attribute('aria-pressed')=='false')
    context.close()
    b.close()
server.shutdown()
report={'checks':len(results),'passed':results,'errors':errors,'speechValidation':'Utterance text, language, rate, queue and cancellation only; no physical iPhone audio test.'}
print(json.dumps(report,ensure_ascii=False,indent=2))
(QA/'report.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
