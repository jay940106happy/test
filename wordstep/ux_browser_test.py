import json, pathlib
from playwright.sync_api import sync_playwright
ROOT=pathlib.Path(__file__).parent
HTML=(ROOT/"index.html").read_text(encoding="utf-8").replace('<script src="./cloud-sync.js" type="module"></script>', "")
STORAGE_JS="""(seed)=>{let data={...seed};Object.defineProperty(window,'localStorage',{configurable:true,value:{getItem:(k)=>data[k]??null,setItem:(k,v)=>{data[k]=String(v)},removeItem:(k)=>{delete data[k]},clear:()=>{data={}},key:(n)=>Object.keys(data)[n]??null,get length(){return Object.keys(data).length}}});window.__storage=()=>({...data});}"""

checks=[]
def check(condition,desc):
    assert condition,desc
    checks.append(desc)
with sync_playwright() as p:
  b=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
  context=b.new_context(viewport={'width':390,'height':844})
  seed={'wordstep.progress.v1':json.dumps({'w0002':True,'w0004':True,'tsl0001':True}),
        'wordstep.preferences.v1':json.dumps({'selected':'w0001','scope':'priority','rate':0.9})}
  page=context.new_page()
  errors=[]
  page.on('pageerror',lambda e:errors.append(str(e)))
  page.evaluate(STORAGE_JS,seed)
  page.set_content(HTML)
  check(page.locator('#show-known').count()==1,'explicit show mastered checkbox exists')
  check(not page.locator('#show-known').is_checked(),'mastered hidden by default')
  check(page.locator('#word-jump option').count()==1296,'pre-existing 3 learned excluded from priority queue')
  check(page.locator('#word').inner_text()=='office','first new word office')
  check(bool(page.evaluate("JSON.parse(localStorage.getItem('wordstep.progress.before-ux.v1')||'{}').w0002")),'pre-upgrade local backup preserved')
  page.locator('#known').click()
  check(page.locator('#word').inner_text()=='employee','mark auto advances, skipping existing learned word')
  check(page.evaluate("JSON.parse(localStorage.getItem('wordstep.progress.v1')).w0001") is True,'new marking stored')
  check(page.evaluate("JSON.parse(localStorage.getItem('wordstep.progress.v1')).w0002") is True,'old record w0002 intact')
  check(page.evaluate("JSON.parse(localStorage.getItem('wordstep.progress.v1')).w0004") is True,'old record w0004 intact')
  check(page.locator('#word-jump option').count()==1295,'marked word leaves study queue')
  check(page.locator('#mark-feedback').is_visible(),'mark feedback shown')
  page.locator('#undo-last').click()
  check(page.locator('#word').inner_text()=='office','undo returns to the word')
  check(page.evaluate("JSON.parse(localStorage.getItem('wordstep.progress.v1')).w0002") is True,'undo preserves unrelated records')
  check(page.locator('#word-jump option').count()==1296,'undo restores study queue')
  page.locator('#search').fill('employee')
  page.locator('#known').click()
  check(page.locator('#empty').is_visible(),'last unlearned item advances to completed state')
  check('已學完' in page.locator('#empty').inner_text(),'completed state shown after marking last')
  page.locator('#undo-last').click()
  check(page.locator('#word').inner_text()=='employee','undo recovers the last learned item')
  page.locator('#search').fill('office')
  page.locator('#known').click()
  page.locator('#search').fill('')
  page.locator('#show-known').check()
  check(page.locator('#word-jump option').count()==1299,'show learned includes all items')
  check(page.locator('#show-known').is_checked(),'show learned checkbox on')
  check(page.evaluate("JSON.parse(localStorage.getItem('wordstep.preferences.v1')).showKnown") is True,'show learned setting saved for cloud prefs')
  saved=page.evaluate("window.__storage()")
  page=context.new_page()
  page.evaluate(STORAGE_JS,saved)
  page.set_content(HTML)
  check(page.locator('#show-known').is_checked(),'show preference persists reload')
  check(page.locator('#word-jump option').count()==1299,'show learned persists')
  page.locator('#show-known').uncheck()
  check(page.locator('#word-jump option').count()==1295,'hide learned returns to learning queue')
  page.locator('#tools').evaluate('(e)=>e.open=true')
  page.select_option('#filter','known')
  check(page.locator('#show-known').is_checked(),'advanced known-only mode enables show learned')
  check(page.locator('#word-jump option').count()==4,'known-only includes original learned and newly marked')
  page.select_option('#filter','new')
  check(not page.locator('#show-known').is_checked(),'advanced new filter hides learned')
  page.select_option('#scope','tsl-new')
  check(page.locator('#word-jump option').count()==299,'TSL new learned excluded')
  page.select_option('#scope','priority')
  page.locator('#search').fill('office')
  check(page.locator('#word').inner_text()!='office','learned office absent in searched results')
  page.locator('#show-known').check()
  check(page.locator('#word').inner_text()=='office','show learned recovers filtered single word')
  page.locator('#show-known').uncheck()
  page.locator('#search').fill('mister')
  page.select_option('#scope','tsl-new')
  check(page.locator('#empty').is_visible(),'no items shows helpful empty state')
  check('已學' in page.locator('#empty').inner_text(),'all mastered state explains completed selection')
  page.locator('#search').fill('')
  for width in (320,390,1280):
    page.set_viewport_size({'width':width,'height':850})
    check(page.evaluate('document.documentElement.scrollWidth<=innerWidth'),f'no horizontal overflow at {width}px')
    if width in (390,1280):page.screenshot(path=str(ROOT/f'ux-{width}.png'),full_page=True)
  check(not errors,f'JS errors: {errors}')
  print('PASS',len(checks),'UX checks')
  b.close()